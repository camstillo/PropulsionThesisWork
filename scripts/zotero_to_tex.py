#!/usr/bin/env python3
"""Write a Zotero collection into sections/literature_search.tex as a longtable.

Usage: python3 scripts/zotero_to_tex.py [--write]

Without --write the table is printed. With --write it replaces everything
between the "% BEGIN ZOTERO" and "% END ZOTERO" markers in the .tex file.
Zotero keeps zotero.sqlite locked while it runs, so a copy is read instead.
"""
import argparse
import re
import shutil
import sqlite3
import tempfile
from pathlib import Path

ZOTERO_DB = Path.home() / "Zotero" / "zotero.sqlite"
TEX_FILE = Path(__file__).resolve().parent.parent / "sections" / "literature_search.tex"
PARENT = "PropulsionThesis"
SUBCOLLECTIONS = ["Bus power", "Thermal Analysis", "Pointing Optimization", "Orbit-Attitude Estimation"]

# Zotero item key -> core / related / background. Anything not listed shows TODO.
TAGS = {}

QUERY = """
SELECT it.key,
  (SELECT v.value FROM itemData d JOIN itemDataValues v USING(valueID) JOIN fields f USING(fieldID)
     WHERE d.itemID = it.itemID AND f.fieldName = 'title'),
  (SELECT substr(v.value, 1, 4) FROM itemData d JOIN itemDataValues v USING(valueID) JOIN fields f USING(fieldID)
     WHERE d.itemID = it.itemID AND f.fieldName = 'date'),
  it.itemID
FROM collections c
JOIN collections p ON c.parentCollectionID = p.collectionID
JOIN collectionItems ci ON ci.collectionID = c.collectionID
JOIN items it ON it.itemID = ci.itemID
WHERE p.collectionName = ? AND c.collectionName = ?
  AND it.itemID NOT IN (SELECT itemID FROM deletedItems)
"""

AUTHORS = """
SELECT cr.lastName FROM itemCreators ic JOIN creators cr USING(creatorID)
JOIN creatorTypes ct USING(creatorTypeID)
WHERE ic.itemID = ? AND ct.creatorType = 'author' ORDER BY ic.orderIndex
"""

ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
           "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(text):
    text = re.sub(r"<[^>]+>", "", text or "")
    return "".join(ESCAPES.get(ch, ch) for ch in text)


def authors(db, item_id):
    names = [r[0] for r in db.execute(AUTHORS, (item_id,)) if r[0]]
    if not names:
        return "---"
    if len(names) > 3:
        return esc(names[0]) + " et al."
    return ", ".join(esc(n) for n in names)


def build_table(db):
    rows, seen = [], set()
    for sub in SUBCOLLECTIONS:
        for key, title, year, item_id in sorted(db.execute(QUERY, (PARENT, sub)).fetchall(),
                                                key=lambda r: (r[2] or "", r[1] or "")):
            if key in seen:
                continue
            seen.add(key)
            rows.append(f"    {esc(sub)} & {authors(db, item_id)} & {year or 'n.d.'} & "
                        f"{esc(title)} & {TAGS.get(key, 'TODO')} \\\\")
    head = [
        f"% {len(rows)} items, generated by scripts/zotero_to_tex.py",
        r"\begin{longtable}{@{}p{0.14\linewidth}p{0.14\linewidth}rp{0.45\linewidth}l@{}}",
        r"  \toprule",
        r"  Folder & Authors & Year & Title & Tag \\",
        r"  \midrule",
        r"  \endhead",
    ]
    return "\n".join(head + rows + [r"  \bottomrule", r"\end{longtable}"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "zotero.sqlite"
        shutil.copy(ZOTERO_DB, copy)
        wal = ZOTERO_DB.with_name("zotero.sqlite-wal")
        if wal.exists():
            shutil.copy(wal, Path(tmp) / "zotero.sqlite-wal")
        db = sqlite3.connect(copy)
        table = build_table(db)
        db.close()
    if not args.write:
        print(table)
        return
    text = TEX_FILE.read_text()
    pattern = re.compile(r"(% BEGIN ZOTERO\n).*?(% END ZOTERO)", re.S)
    if not pattern.search(text):
        raise SystemExit("Markers not found in " + str(TEX_FILE))
    TEX_FILE.write_text(pattern.sub(lambda m: m.group(1) + table + "\n" + m.group(2), text))
    print("Wrote table to", TEX_FILE)


if __name__ == "__main__":
    main()
